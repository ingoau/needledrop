"""Prepare beets for Needledrop at startup.

- With no `config.yaml` in the beets config folder, write Needledrop's
  opinionated default.
- Generate an overlay (layered with `beet -c`) that loads the bundled plugins
  first and fixes up paths that only make sense on the host, so an existing
  beets setup can be mounted as-is.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import yaml

from . import db
from .config import settings

DEFAULT_CONFIG = """\
# Written by Needledrop on first start. Edit freely; Needledrop only layers
# its own plugin folder (and LIBRARY_DIR, if set) on top of this file.

directory: {library}
library: {beets_dir}/library.db

plugins:
  - musicbrainz
  - chroma          # acoustic fingerprints; needs fpcalc (bundled)
  - spotify         # a second metadata source for releases MusicBrainz lacks
  - filetote        # moves .ttml/.lrc lyrics along with their tracks
  - searchfix       # bundled: cleaner MusicBrainz/Spotify queries for Apple rips

import:
  move: yes
  write: yes
  duplicate_action: skip

paths:
  default: $albumartist/$year - $album%aunique{{}}/$disc-$track - $title
  singleton: $artist/Non-Album/$title
  comp: Compilations/$year - $album%aunique{{}}/$disc-$track - $title

filetote:
  pairing:
    enabled: true
    pairing_only: true
    extensions: .ttml .lrc .elrc

chroma:
  auto: yes

musicbrainz:
  data_source_mismatch_penalty: 0.0

# Spotify matches never auto-apply; they wait in the Inbox for a click.
spotify:
  data_source_mismatch_penalty: 1.0
"""


def prepare() -> None:
    beets_dir = settings.beets_dir
    beets_dir.mkdir(parents=True, exist_ok=True)
    config_path = beets_dir / "config.yaml"
    if not os.access(beets_dir, os.W_OK):
        raise SystemExit(
            f"Needledrop can't write to {beets_dir} (mounted from BEETS_PATH). "
            f"Create the folder before starting, owned by the PUID:PGID the "
            f"container runs as (uid {os.getuid()})."
        )
    if not config_path.exists():
        library = settings.library_dir or str(settings.music_dir / "library")
        config_path.write_text(
            DEFAULT_CONFIG.format(library=library, beets_dir=beets_dir)
        )
        db.log("info", "system", f"Wrote a default beets config to {config_path}")

    try:
        user = yaml.safe_load(config_path.read_text()) or {}
    except yaml.YAMLError as exc:
        db.log("error", "system", f"Can't read {config_path}: {exc}")
        user = {}

    overlay: dict[str, Any] = {}

    # Bundled plugins first, so they win over copies elsewhere.
    plugin_paths = [settings.beet_plugins]
    configured = user.get("pluginpath") or []
    if isinstance(configured, str):
        configured = [configured]
    plugin_paths += [p for p in configured if Path(p).is_dir()]
    overlay["pluginpath"] = plugin_paths

    # A library path from the host that doesn't exist here: look for the
    # database next to the config instead.
    library = user.get("library")
    if library and not Path(library).parent.is_dir():
        overlay["library"] = str(beets_dir / Path(library).name)

    if settings.library_dir:
        overlay["directory"] = settings.library_dir

    settings.beet_overlay.parent.mkdir(parents=True, exist_ok=True)
    settings.beet_overlay.write_text(
        "# Generated by Needledrop at startup; changes are overwritten.\n"
        + yaml.safe_dump(overlay, sort_keys=False)
    )
